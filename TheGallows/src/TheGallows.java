    private static void game(String secretWord) throws IOException {
        int countLifeGame = 6;
        String[] guessedLetters = new String[secretWord.length()];
        for (int i = 0; i < secretWord.length(); i++) {
            guessedLetters[i] = "*";
        }

        while (countLifeGame > 0){
            System.out.println("\n------------------------------------------------");
            victim(countLifeGame);
            System.out.println("Загаданное слово :D");
            for (String i: guessedLetters) System.out.print(i);
            System.out.print("\nВведите букву (Enter the letter): ");
            String userLetter = reader.readLine().trim().toLowerCase();


            if (userLetter.length() != 1){
                System.out.println("ERROR! Неверный ввод (Введите ОДНУ букву)" + "\n");
                continue;
            }

            if (secretWord.toLowerCase().contains(userLetter)){
                for (int i = 0; i < secretWord.length(); i++) {
                    if (userLetter.charAt(0) == secretWord.toLowerCase().charAt(i)){
                        guessedLetters[i] = userLetter;
                    }
                }
            }else{
                countLifeGame--;
                if (countLifeGame == 0){
                    System.out.println("\n-----------------------------------------");
                    victim(countLifeGame); //чтобы вывел картинку смерти
                    System.out.println("Загаданное слово :D \n     " + secretWord);
                }
            }

            StringBuilder flag = new StringBuilder();
            for (String i: guessedLetters){
                flag.append(i);
            }
            if (secretWord.equalsIgnoreCase(flag.toString())){
                System.out.println("\n----------------------------------------------------");
                System.out.println(
                        """
                                |||||||||||||||||
                                ||   /    |
                                ||  /     |
                                || /   You won :)
                                ||/   ПОБЕДА!!!!!!!
                                ||
                                ||      (*_*)
                                ||    *-(.Y.)-*
                                ||The game is over
                                ||Игра окончена"""
                );
                break;
            };
        }
    }

